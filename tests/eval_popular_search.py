"""Replay real queries and report the ones that come back empty.

Takes the output of get_popular_search.py.  A query that users typed often and
that returns nothing is the strongest available signal of a recall bug; every
such case is printed with the tier the engine stopped at, so it is clear
whether the ladder ran out of rungs or the term genuinely does not occur.

    PYTHONPATH=. python3 tests/get_popular_search.py > /tmp/popular.txt
    PYTHONPATH=. python3 tests/eval_popular_search.py /tmp/popular.txt
"""

import argparse
import re

from tqdm import tqdm

from app import app
from app.search import MatchQuality, search_courses, search_reviews

REG = re.compile(r"(.+): (\d+) \((\d+) / (\d+)\)")


class AnonymousUser:
    is_authenticated = False
    identity = "Anonymous"
    id = None


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Eval popular search queries")
    parser.add_argument(
        "file", type=str, help="search query file generated by get_popular_search.py"
    )
    parser.add_argument(
        "--min-count", type=int, default=10, help="only replay queries seen this often"
    )
    args = parser.parse_args()

    anon = AnonymousUser()
    empty, relaxed, checked = [], [], 0
    with open(args.file, "r") as fh:
        with app.app_context():
            for line in tqdm(fh):
                m = REG.match(line)
                if not m:
                    continue
                query, total = m.group(1), int(m.group(2))
                course_cnt = int(m.group(3))
                if total <= args.min_count:
                    continue
                checked += 1
                courses = search_courses(query, 1, 10)
                reviews = search_reviews(query, 1, 10, anon)
                if courses.total == 0 and reviews.total == 0:
                    empty.append((query, total))
                elif course_cnt and courses.quality < MatchQuality.EXACT:
                    relaxed.append((query, courses.quality.name, courses.tier))

    print(f"\nreplayed {checked} queries")
    print(f"  returned nothing: {len(empty)}")
    for query, count in empty[:40]:
        print(f"    {query!r} (searched {count}x)")
    print(f"  answered only after relaxing: {len(relaxed)}")
    for query, quality, tier in relaxed[:40]:
        print(f"    {query!r} -> {quality} via {tier}")
